#!/usr/bin/env node
// Publishes the /nereye-gitti images from the app repo's ready-made web
// copies of the App Store frames (gidertakip docs/magaza/web/), byte for byte,
// and writes the manifest the pages read. Run from the repo root:
//
//   node scripts/nereye-gitti-screenshots.mjs [source-dir]
//
// Source: [source-dir], else gidertakip docs/magaza/web/ (extract it from a
// commit with `git -C … archive <ref> docs/magaza/web | tar -x` when the
// working copy lags). For the six frames (01-… to 06-…, file-name order =
// App Store order) it copies <name>-{660,1320}.{webp,jpg} to
// public/nereye-gitti/ekranlar/<name>-<w>.<sha8>.<ext>, and
// og-nereye-gitti-1200x630.png to public/nereye-gitti/og.<sha8>.png and
// og.png (the plain name older shares point at). Hashed names change with
// the content, so they are served as immutable. After a deploy, purge
// /nereye-gitti/og.png on Cloudflare. Check captions/alts in
// app/nereye-gitti/_lib/screenshots.ts against the frames.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const APP_WEB = "/Users/atakan/Projects/gidertakip/docs/magaza/web";
const PUB = path.join(ROOT, "public/nereye-gitti");
const OUT_DIR = path.join(PUB, "ekranlar");
const MANIFEST = path.join(ROOT, "app/nereye-gitti/_lib/screenshots.generated.ts");
const VARIANTS = ["660.webp", "1320.webp", "660.jpg", "1320.jpg"];
const OG_SOURCE = "og-nereye-gitti-1200x630.png";

const sourceDir = process.argv[2] || APP_WEB;
const names = fs.existsSync(sourceDir)
  ? [...new Set(fs.readdirSync(sourceDir).map((f) => f.match(/^(\d\d-.+)-660\.webp$/)?.[1]).filter(Boolean))].sort()
  : [];
if (names.length !== 6 || !fs.existsSync(path.join(sourceDir, OG_SOURCE))) {
  console.error(`Expected 6 frames and ${OG_SOURCE} in ${sourceDir}; found ${names.length} frames. Nothing written.`);
  process.exit(1);
}

const sha8 = (buf) => crypto.createHash("sha256").update(buf).digest("hex").slice(0, 8);

/** Copies `file` into `dir` as <stem>.<sha8>.<ext>; returns the public URL path. */
const publish = (file, dir, stem) => {
  const buf = fs.readFileSync(file);
  const ext = path.extname(file);
  const name = `${stem}.${sha8(buf)}${ext}`;
  fs.writeFileSync(path.join(dir, name), buf);
  console.log(`  ${name}  ${(buf.length / 1024).toFixed(0)} KB`);
  return `/${path.relative(path.join(ROOT, "public"), path.join(dir, name))}`;
};

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const frames = names.map((name) => {
  const urls = Object.fromEntries(
    VARIANTS.map((v) => {
      const file = path.join(sourceDir, `${name}-${v}`);
      if (!fs.existsSync(file)) throw new Error(`Missing ${file}`);
      const [w, ext] = v.split(".");
      return [`${ext}${w}`, publish(file, OUT_DIR, `${name}-${w}`)];
    }),
  );
  return `  ${JSON.stringify(urls)},`;
});

for (const f of fs.readdirSync(PUB)) if (/^og\.[0-9a-f]{8}\.png$/.test(f)) fs.rmSync(path.join(PUB, f));
const ogFile = path.join(sourceDir, OG_SOURCE);
const og = publish(ogFile, PUB, "og");
fs.copyFileSync(ogFile, path.join(PUB, "og.png"));

fs.writeFileSync(
  MANIFEST,
  `// Generated by scripts/nereye-gitti-screenshots.mjs — do not edit by hand.
// Source: ${sourceDir.replace(/\/+$/, "").endsWith("docs/magaza/web") ? "gidertakip docs/magaza/web" : sourceDir}/ (${names.join(", ")}, ${OG_SOURCE})
export type ScreenshotFiles = { webp660: string; webp1320: string; jpg660: string; jpg1320: string };

export const SCREENSHOT_FILES: readonly ScreenshotFiles[] = [
${frames.join("\n")}
];

/** Share image (og:image / twitter:image), content-hashed. */
export const OG_IMAGE_PATH = ${JSON.stringify(og)};
`,
);
console.log(`Wrote ${path.relative(ROOT, MANIFEST)}`);
